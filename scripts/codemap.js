/**
 * Purpose: generate docs/CODEMAP.md from the repository tree using Node built-ins.
 * Owner: builder-grok
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CODEMAP_REL = 'docs/CODEMAP.md';

const SKIP_DIR_NAMES = new Set(['.git', 'node_modules']);
const SKIP_PREFIXES = ['web/assets/', 'docs/images/', 'page/src/icons/'];
const SKIP_EXT = new Set(['.png', '.woff2', '.jpg', '.jpeg', '.gif', '.webp']);

export function toPosix(rel) {
  return rel.split(path.sep).join('/');
}

export function shouldSkip(rel, isDir) {
  if (!rel) return true;
  const posix = toPosix(rel);
  if (posix === CODEMAP_REL) return true;
  const base = path.basename(posix);
  if (SKIP_DIR_NAMES.has(base)) return true;
  if (posix.startsWith('.') && posix !== '.github' && !posix.startsWith('.github/')) {
    return true;
  }
  for (const prefix of SKIP_PREFIXES) {
    if (posix === prefix.slice(0, -1) || posix.startsWith(prefix)) return true;
  }
  if (!isDir && SKIP_EXT.has(path.extname(posix).toLowerCase())) return true;
  return false;
}

export function walk(dir, root, acc = []) {
  const names = fs.readdirSync(dir).sort((a, b) => a.localeCompare(b));
  for (const name of names) {
    const full = path.join(dir, name);
    const rel = toPosix(path.relative(root, full));
    const isDir = fs.statSync(full).isDirectory();
    if (shouldSkip(rel, isDir)) continue;
    acc.push({ rel, isDir });
    if (isDir) walk(full, root, acc);
  }
  return acc;
}

function localImports(root, fileRel) {
  const text = fs.readFileSync(path.join(root, fileRel), 'utf8');
  const found = [];
  const re = /from\s+['"](\.[^'"]+)['"]/g;
  let m = re.exec(text);
  while (m) {
    found.push(m[1]);
    m = re.exec(text);
  }
  return [...new Set(found)].sort((a, b) => a.localeCompare(b));
}

function readmePurpose(root, dirRel) {
  const full = path.join(root, dirRel, 'README.md');
  if (!fs.existsSync(full)) return '';
  const lines = fs.readFileSync(full, 'utf8').split(/\r?\n/);
  for (const line of lines) {
    if (line.startsWith('Purpose:')) return line.slice('Purpose:'.length).trim();
  }
  return '';
}

export function generateCodemapText(root = ROOT) {
  const entries = walk(root, root);
  const lines = [];
  lines.push('# CODEMAP');
  lines.push('');
  lines.push('Generated by `npm run codemap` (`scripts/codemap.js`). Do not edit by hand.');
  lines.push('Vendor binaries under `web/assets/`, `docs/images/` and `page/src/icons/` are omitted.');
  lines.push('');
  lines.push('## Modules');
  lines.push('');
  lines.push('| Path | Purpose |');
  lines.push('|---|---|');
  for (const e of entries) {
    if (!e.isDir) continue;
    if (e.rel.includes('/')) continue;
    const purpose = readmePurpose(root, e.rel) || '(no README)';
    lines.push(`| \`${e.rel}/\` | ${purpose} |`);
  }
  lines.push('');
  lines.push('## Tree');
  lines.push('');
  for (const e of entries) {
    lines.push(e.isDir ? `- \`${e.rel}/\`` : `- \`${e.rel}\``);
  }
  lines.push('');
  lines.push('## src imports');
  lines.push('');
  const srcFiles = entries
    .filter((e) => !e.isDir && e.rel.startsWith('src/') && e.rel.endsWith('.js'))
    .map((e) => e.rel);
  for (const fileRel of srcFiles) {
    const imps = localImports(root, fileRel);
    const list = imps.length ? imps.map((i) => `\`${i}\``).join(', ') : '(none)';
    lines.push(`- \`${fileRel}\`: ${list}`);
  }
  lines.push('');
  return lines.join('\n');
}

export function writeCodemap(root = ROOT) {
  const text = generateCodemapText(root);
  const out = path.join(root, CODEMAP_REL);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, text);
  return out;
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  writeCodemap();
}
